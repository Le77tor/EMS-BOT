/**
 * Получить название ранга по ID роли
 */
export function getRankName(roleId: string): string | null {
  return ROLE_TO_RANK[roleId] || null;
}

/**
 * Получить текущий ранг пользователя из списка его ролей
 */
export function getCurrentRank(userRoles: string[]): string {
  // Ищем первую роль, которая является рангом
  for (const roleId of userRoles) {
    const rankName = getRankName(roleId);
    if (rankName) {
      return rankName;
    }
  }
  return 'Не указан';
}

/**
 * Определить отдел по префиксу в нике
 */
export function getDepartmentFromPrefix(displayName: string): DepartmentType | 'UNKNOWN' {
  const prefix = displayName.split('|')[0]?.trim();
  return DEPARTMENT_PREFIXES[prefix] || 'UNKNOWN';
}
